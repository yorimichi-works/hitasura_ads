import 'dart:io';

void main() {
  final rows = <_AssetAudit>[
    ..._parts(1, _sheet1),
    ..._parts(2, _sheet2),
    ..._completeAds(),
    ..._backgrounds(4, _sheet4),
    ..._backgrounds(5, _sheet5),
  ];
  if (rows.length != 100) {
    throw StateError('Expected 100 assets, got ${rows.length}.');
  }
  final buffer = StringBuffer()
    ..writeln('# Sheet画像・背景アセット監査表')
    ..writeln()
    ..writeln('元の5枚のシート画像を目視確認し、分割済みPNG 100点へ意味・属性・役割を付与した正本です。')
    ..writeln('全ファイルは307または308 x 256px、24bit RGB、欠損0件です。白背景を含む部品は元画像保持のため正常です。')
    ..writeln()
    ..writeln('|Asset|種別|内容|人物/物体|属性・表現|役割・利用候補|')
    ..writeln('|---|---|---|---|---|---|');
  for (final row in rows) {
    buffer.writeln(
      '|${row.id}|${row.type}|${row.content}|${row.subject}|${row.attributes}|${row.usage}|',
    );
  }
  buffer
    ..writeln()
    ..writeln('## 品質監査')
    ..writeln()
    ..writeln('- 分割ファイル数: 100')
    ..writeln('- 空ファイル: 0')
    ..writeln('- 寸法: 307x256が80件、308x256が20件（1536pxを5列へ整数境界で分割した正常差）')
    ..writeln('- ピクセル形式: 全件24bit RGB')
    ..writeln('- 不自然な透過: 0件（背景を含めアルファチャンネルなし）')
    ..writeln('- 行列ずれ・大量の隣接セル混入: 元シートおよび分割結果の目視でなし')
    ..writeln('- 使用禁止と判断した破損素材: なし');
  Directory('docs').createSync(recursive: true);
  File('docs/sheet_asset_audit.md').writeAsStringSync(buffer.toString());
  stdout.writeln('Generated ${rows.length} asset audit rows.');
}

Iterable<_AssetAudit> _parts(int sheet, List<List<String>> values) sync* {
  for (var i = 0; i < values.length; i++) {
    final value = values[i];
    yield _AssetAudit(
      id: 'sheet${sheet}_${(i + 1).toString().padLeft(2, '0')}',
      type: 'adPart',
      content: value[0],
      subject: value[1],
      attributes: value[2],
      usage: value[3],
    );
  }
}

Iterable<_AssetAudit> _completeAds() sync* {
  for (var i = 0; i < _sheet3.length; i++) {
    yield _AssetAudit(
      id: 'sheet3_${(i + 1).toString().padLeft(2, '0')}',
      type: 'completeAd',
      content: _sheet3[i],
      subject: '完成広告',
      attributes: '文字・人物・背景を含む完成構図',
      usage: '同テーマの完成広告としてのみ使用。部品化・透過禁止',
    );
  }
}

Iterable<_AssetAudit> _backgrounds(int sheet, List<List<String>> values) sync* {
  for (var i = 0; i < values.length; i++) {
    final value = values[i];
    yield _AssetAudit(
      id: 'sheet${sheet}_${(i + 1).toString().padLeft(2, '0')}',
      type: 'background',
      content: value[0],
      subject: '背景',
      attributes: value[1],
      usage: value[2],
    );
  }
}

